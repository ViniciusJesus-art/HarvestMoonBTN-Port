"""Regenerate the embedded antialiased menu atlas from Liberation Sans Regular.

Only asset regeneration needs Pillow; normal Linux/Windows builds use the
checked-in atlas with no font library or system-font dependency at runtime.
Usage: python bake_menu_font.py LiberationSans-Regular.ttf native_font_atlas.inc
Font license: port/assets/fonts/LIBERATION-LICENSE.txt.
"""
from pathlib import Path
import hashlib
import sys
from PIL import Image, ImageDraw, ImageFont

source, destination = map(Path, sys.argv[1:])
size, width, pad = 64, 1024, 3
font = ImageFont.truetype(str(source), size)
codes = list(range(32, 127)) + list(range(160, 256)) + [0x2013, 0x2014, 0x2022, 0x2026, 0x2190, 0x2191, 0x2192, 0x2193]
glyphs = []
x = y = pad
row_height = 0
for code in codes:
    left, top, right, bottom = font.getbbox(chr(code), anchor="ls")
    w, h = right - left, bottom - top
    if x + w + pad > width:
        x, y, row_height = pad, y + row_height + pad * 2, 0
    glyphs.append((code, x, y, w, h, left, top, font.getlength(chr(code))))
    x += w + pad * 2
    row_height = max(row_height, h)
height = 1 << (y + row_height + pad - 1).bit_length()
atlas = Image.new("L", (width, height))
draw = ImageDraw.Draw(atlas)
for code, x, y, w, h, left, top, advance in glyphs:
    draw.text((x-left, y-top), chr(code), font=font, anchor="ls", fill=255)
raw = atlas.tobytes()
runs = bytearray()
start = 0
while start < len(raw):
    end = start + 1
    while end < len(raw) and end - start < 255 and raw[end] == raw[start]:
        end += 1
    runs.extend((end-start, raw[start]))
    start = end
lines = ["/* Generated by packaging/bake_menu_font.py; Liberation Sans Regular, SIL OFL 1.1.",
         " * See assets/fonts/LIBERATION-LICENSE.txt.",
         f" * Font SHA-256: {hashlib.sha256(source.read_bytes()).hexdigest()} */",
         f"enum {{ FONT_WIDTH={width},FONT_HEIGHT={height},FONT_SIZE={size},FONT_ASCENT={font.getmetrics()[0]} }};",
         "static const struct FontGlyph font_glyphs[]={"]
for code, x, y, w, h, left, top, advance in glyphs:
    lines.append(f"    {{{code},{x},{y},{w},{h},{left},{top},{advance:.6f}f}},")
lines += ["};", "static const unsigned char font_alpha_runs[]={"]
for offset in range(0, len(runs), 32):
    lines.append("    " + ",".join(map(str, runs[offset:offset+32])) + ",")
lines += ["};", ""]
destination.write_text("\n".join(lines), encoding="utf-8")
print(f"Atlas: {width}x{height}, {len(glyphs)} glyphs, {len(runs)} encoded bytes")
